def export_forecast(
    results: Sequence[ForecastResult],
    path: str | Path,
    *,
    company: str = "",
    sources: dict[str, str] | None = None,
) -> Path:
    """Write a linked three-statement model with a scenario selector."""
    if not results:
        raise ValueError("Nothing to export")
    wb = Workbook()
    asm = wb.active
    asm.title = "Assumptions"
    refs = _assumptions_sheet(asm, results, company, sources or {})
    _model_sheet(wb.create_sheet("Model"), results[0], refs, company)
    _scenario_summary(wb.create_sheet("Scenario summary"), results, company)
    for ws in wb.worksheets:
        ws.sheet_properties.tabColor = theme.xl(theme.GREEN)
        ws.page_setup.orientation = "landscape"
        ws.sheet_properties.pageSetUpPr.fitToPage = True
    path = Path(path)
    wb.save(path)
    return path


def _assumptions_sheet(
    ws: Worksheet, results: Sequence[ForecastResult], company: str, sources: dict[str, str]
) -> dict[str, str]:
    names = [r.scenario for r in results]
    ncols = 3 + len(names) + 1
    _title(
        ws,
        f"{company or 'Forecast'}: assumptions",
        "Change any blue input. Pick the scenario the Model tab runs in cell C4.",
        ncols,
    )
    ws.column_dimensions["A"].width = 44
    ws.column_dimensions["B"].width = 4
    for i in range(len(names) + 1):
        ws.column_dimensions[get_column_letter(3 + i)].width = 14
    ws.column_dimensions[get_column_letter(4 + len(names))].width = 44
    ws["A4"] = "Active scenario"
    ws["A4"].font = BOLD
    ws["C4"] = names[0]
    ws["C4"].font = _font(bold=True, color=theme.xl(theme.INPUT_BLUE))
    ws["C4"].fill = TINT_FILL
    dv = DataValidation(
        type="list",
        formula1='"' + ",".join(names) + '"',
        allow_blank=False,
        showErrorMessage=True,
        errorTitle="Unknown scenario",
        error="Pick one of: " + ", ".join(names),
    )
    ws.add_data_validation(dv)
    dv.add("C4")
    ppy = periods_per_year(results[0].periods[0])
    ws["A5"] = "Periods per year"
    ws["C5"] = ppy
    ws["C5"].font = INPUT
    ws["A6"] = "Days per period"
    ws["C6"] = "=365/C5"
    ws["C6"].number_format = DAYS
    header_row = 8
    active_col = 3 + len(names)
    _header(ws, header_row, ["Driver", "", *names, "Active", "Source"])
    refs: dict[str, str] = {"ppy": "Assumptions!$C$5", "days": "Assumptions!$C$6"}
    first_name = get_column_letter(3)
    last_name = get_column_letter(2 + len(names))
    act = get_column_letter(active_col)
    for i, f in enumerate(fields(Assumptions)):
        r = header_row + 1 + i
        ws.cell(r, 1, ASSUMPTION_LABELS[f.name]).alignment = Alignment(indent=1)
        fmt = (
            PCT2
            if f.name in PERCENT_ASSUMPTIONS
            else (DAYS if f.name in ("dso", "dio", "dpo") else NUM)
        )
        for j, res in enumerate(results):
            c = ws.cell(r, 3 + j, float(getattr(res.assumptions, f.name)))
            c.font = INPUT
            c.number_format = fmt
        a = ws.cell(
            r,
            active_col,
            f"=INDEX({first_name}{r}:{last_name}{r},MATCH($C$4,${first_name}${header_row}:${last_name}${header_row},0))",
        )
        a.font = BOLD
        a.number_format = fmt
        a.fill = TINT_FILL
        ws.cell(r, active_col + 1, sources.get(f.name, "")).font = MUTED
        refs[f.name] = f"Assumptions!${act}${r}"
    _footer(ws, header_row + len(fields(Assumptions)) + 2)
    return refs


def _model_sheet(ws: Worksheet, base: ForecastResult, a: dict[str, str], company: str) -> None:
    periods = base.periods
    _title(
        ws,
        f"{company or 'Forecast'}: three-statement model",
        "Every forecast cell is a formula of the Assumptions tab and the prior column.",
        2 + len(periods),
    )
    ws.column_dimensions["A"].width = 40
    _header(ws, 4, ["", f"{base.opening_period} (opening)", *periods])
    for c in range(2, 3 + len(periods)):
        ws.column_dimensions[get_column_letter(c)].width = 14
    ws.freeze_panes = "C5"
    row: dict[str, int] = {}
    r = 5
    for key, label in _MODEL_ROWS:
        if key == "h":
            cell = ws.cell(r, 1, label)
            cell.font = _font(bold=True, color=theme.xl(theme.GREEN_DARK))
            r += 1
            continue
        if key:
            row[key] = r
            ws.cell(r, 1, label).alignment = Alignment(indent=0 if key in _TOTALS else 1)
            if key in _TOTALS:
                ws.cell(r, 1).font = BOLD
        r += 1
    # Opening column: last actual balances as inputs; flows that seed growth.
    for key, rr in row.items():
        c = ws.cell(rr, 2)
        if key in _OPENING_KEYS:
            c.value = _num(base.opening.get(_OPENING_KEYS[key], Decimal(0)))
            c.font = INPUT
        c.number_format = NUM
    for key in ("total_assets", "total_liabilities", "total_le"):
        ws.cell(row[key], 2, _bs_total(key, "B", row)).font = BOLD
    ws.cell(row["chk_bs"], 1, "Balance sheet balances (net of opening gap)")
    ws.cell(row["chk_bs"], 2, f"=ROUND(B{row['total_assets']}-B{row['total_le']},2)")
    ws.cell(row["chk_bs"], 2).number_format = NUM2

    for i in range(len(periods)):
        col = get_column_letter(3 + i)
        p = get_column_letter(2 + i)

        def at(k: str, col: str = col) -> str:
            return f"{col}{row[k]}"

        def prev(k: str, p: str = p) -> str:
            return f"{p}{row[k]}"

        pre = f"{prev('cash')}+{at('cfo')}+{at('cfi')}+{at('cf_debt')}+{at('cf_div')}"
        f: dict[str, str] = {
            "revenue": f"={prev('revenue')}*(1+{a['revenue_growth']})",
            "cogs": f"={at('revenue')}*(1-{a['gross_margin']})",
            "gross_profit": f"={at('revenue')}-{at('cogs')}",
            "opex": f"={at('revenue')}*{a['opex_pct_revenue']}+{a['fixed_opex']}",
            "ebitda": f"={at('gross_profit')}-{at('opex')}",
            "da": f"={prev('ppe')}*{a['depreciation_rate']}",
            "operating_income": f"={at('ebitda')}-{at('da')}",
            "interest": f"=({prev('debt')}+{prev('revolver')})*{a['interest_rate_annual']}/{a['ppy']}",
            "pretax": f"={at('operating_income')}-{at('interest')}",
            "tax": f"=MAX({at('pretax')},0)*{a['tax_rate']}",
            "net_income": f"={at('pretax')}-{at('tax')}",
            "ar": f"={at('revenue')}*{a['dso']}/{a['days']}",
            "inventory": f"={at('cogs')}*{a['dio']}/{a['days']}",
            "ap": f"={at('cogs')}*{a['dpo']}/{a['days']}",
            "ppe": f"={prev('ppe')}-{at('capex')}-{at('da')}",
            "debt": f"={prev('debt')}+{a['debt_change']}",
            "equity": f"={prev('equity')}+{at('net_income')}-{a['dividends']}",
            "oca": f"={prev('oca')}",
            "oa": f"={prev('oa')}",
            "accrued": f"={prev('accrued')}",
            "deferred": f"={prev('deferred')}",
            "ol": f"={prev('ol')}",
            "cf_ni": f"={at('net_income')}",
            "cf_da": f"={at('da')}",
            "cf_ar": f"=-({at('ar')}-{prev('ar')})",
            "cf_inv": f"=-({at('inventory')}-{prev('inventory')})",
            "cf_ap": f"={at('ap')}-{prev('ap')}",
            "cfo": f"=SUM({col}{row['cf_ni']}:{col}{row['cf_ap']})",
            "capex": f"=-{at('revenue')}*{a['capex_pct_revenue']}",
            "cfi": f"={at('capex')}",
            "cf_debt": f"={a['debt_change']}",
            "cf_div": f"=-{a['dividends']}",
            "cf_rev": (
                f"=MAX({a['minimum_cash']}-({pre}),0)"
                f"-MIN({prev('revolver')},MAX(({pre})-{a['minimum_cash']},0))"
            ),
            "revolver": f"={prev('revolver')}+{at('cf_rev')}",
            "cff": f"={at('cf_debt')}+{at('cf_div')}+{at('cf_rev')}",
            "net_change": f"={at('cfo')}+{at('cfi')}+{at('cff')}",
            "fcf": f"={at('cfo')}+{at('capex')}",
            "cash": f"={prev('cash')}+{at('net_change')}",
            "total_assets": _bs_total("total_assets", col, row),
            "total_liabilities": _bs_total("total_liabilities", col, row),
            "total_le": _bs_total("total_le", col, row),
            "chk_bs": f"=ROUND(({at('total_assets')}-{at('total_le')})-($B${row['total_assets']}-$B${row['total_le']}),2)",
            "chk_cash": f"=ROUND({prev('cash')}+{at('net_change')}-{at('cash')},2)",
        }
        for key, formula in f.items():
            c = ws.cell(row[key], 3 + i, formula)
            c.font = BOLD if key in _TOTALS else FORMULA
            c.number_format = NUM2 if key.startswith("chk") else NUM
    for key in _TOTALS:
        for c in range(1, 3 + len(periods)):
            ws.cell(row[key], c).border = Border(top=RULE)
    last_col = get_column_letter(2 + len(periods))
    for key in ("chk_bs", "chk_cash"):
        ws.conditional_formatting.add(
            f"B{row[key]}:{last_col}{row[key]}",
            CellIsRule(
                operator="notEqual",
                formula=["0"],
                fill=PatternFill("solid", fgColor=theme.xl(theme.UNFAVORABLE_BG)),
            ),
        )
    ws.cell(row["chk_bs"], 2).font = MUTED
    _footer(ws, row["chk_cash"] + 2)


def _bs_total(key: str, col: str, row: dict[str, int]) -> str:
    parts = {
        "total_assets": ("cash", "ar", "inventory", "oca", "ppe", "oa"),
        "total_liabilities": ("ap", "accrued", "deferred", "debt", "revolver", "ol"),
        "total_le": ("total_liabilities", "equity"),
    }[key]
    return "=" + "+".join(f"{col}{row[k]}" for k in parts)


def _scenario_summary(ws: Worksheet, results: Sequence[ForecastResult], company: str) -> None:
    _title(
        ws,
        f"{company or 'Forecast'}: scenario summary",
        f"Totals for {results[0].periods[0]} to {results[0].periods[-1]}, computed by "
        "OpenVariance for each scenario (values; the Model tab is live).",
        1 + len(results),
    )
    ws.column_dimensions["A"].width = 34
    _header(ws, 4, ["", *(r.scenario for r in results)])
    metrics = (
        ("Revenue", "revenue", False),
        ("Gross profit", "gross_profit", False),
        ("Gross margin", "gross_margin", True),
        ("EBITDA", "ebitda", False),
        ("EBITDA margin", "ebitda_margin", True),
        ("Net income", "net_income", False),
        ("Free cash flow", "free_cash_flow", False),
        ("Ending cash", "cash", False),
    )
    for i, res in enumerate(results):
        ws.column_dimensions[get_column_letter(2 + i)].width = 16

        def total(k: str, res: ForecastResult = res) -> Decimal:
            return sum((res.values[p][k] for p in res.periods), Decimal(0))

        revenue = total("revenue")
        values = {
            "revenue": revenue,
            "gross_profit": total("gross_profit"),
            "gross_margin": total("gross_profit") / revenue if revenue else Decimal(0),
            "ebitda": total("ebitda"),
            "ebitda_margin": total("ebitda") / revenue if revenue else Decimal(0),
            "net_income": total("net_income"),
            "free_cash_flow": total("free_cash_flow"),
            "cash": res.values[res.periods[-1]]["cash"],
        }
        for j, (label, key, is_pct) in enumerate(metrics):
            r = 5 + j
            ws.cell(r, 1, label).alignment = Alignment(indent=1)
            v = values[key]
            c = ws.cell(r, 2 + i, float(v.quantize(Decimal("0.0001"))) if is_pct else _num(v))
            c.number_format = PCT if is_pct else NUM
    r = 5 + len(metrics) + 1
    ws.cell(r, 1, "Checks passed").font = BOLD
    for i, res in enumerate(results):
        ws.cell(r, 2 + i, "Yes" if res.balanced else "No").font = BOLD
    _footer(ws, r + 2)
