"""Excel workbooks a finance team can audit: live formulas, inputs in blue, checks that tie.

Two workbooks:

* :func:`export_variance` - Dashboard, Variance (with department drill-down),
  Bridge and Notes tabs. Totals, variances, percentages and F/U flags are
  formulas, so editing an actual or budget number updates the whole report.
* :func:`export_forecast` - Assumptions (Base, Upside and Downside columns with
  a scenario selector), a fully linked three-statement Model, and a Scenario
  summary. The Model reproduces the Python engine cell for cell, and the test
  suite recalculates it to prove it.

Conventions: blue font is a hard-coded input, black is a formula; negatives
are in parentheses; every check cell should read 0.
"""

