FONT = "Calibri"
HEADER_FILL = PatternFill("solid", fgColor=theme.xl(theme.GREEN))
TITLE_FILL = PatternFill("solid", fgColor=theme.xl(theme.GREEN))
TINT_FILL = PatternFill("solid", fgColor=theme.xl(theme.GREEN_TINT))
RULE = Side(style="thin", color=theme.xl(theme.GREEN_RULE))
TOTAL_RULE = Side(style="medium", color=theme.xl(theme.GREEN))


def _font(**kw: Any) -> Font:
    return Font(name=FONT, size=kw.pop("size", 11), **kw)


INPUT = _font(color=theme.xl(theme.INPUT_BLUE))
FORMULA = _font(color=theme.xl(theme.INK))
BOLD = _font(bold=True, color=theme.xl(theme.INK))
MUTED = _font(color=theme.xl(theme.INK_MUTED), size=10)
WHITE_BOLD = _font(bold=True, color=theme.xl(theme.WHITE))


def _title(ws: Worksheet, title: str, subtitle: str, width: int) -> None:
    ws.sheet_view.showGridLines = False
    end = get_column_letter(width)
    ws.merge_cells(f"A1:{end}1")
    ws["A1"] = title
    ws["A1"].font = _font(bold=True, size=16, color=theme.xl(theme.WHITE))
    ws["A1"].fill = TITLE_FILL
    ws["A1"].alignment = Alignment(vertical="center", indent=1)
    ws.row_dimensions[1].height = 30
    for c in range(2, width + 1):
        ws.cell(1, c).fill = TITLE_FILL
    ws.merge_cells(f"A2:{end}2")
    ws["A2"] = subtitle
    ws["A2"].font = MUTED
    ws["A2"].alignment = Alignment(indent=1)


TEXT_HEADERS = {"Detail", "Source", "Driver", "Step", "Line"}


def _header(ws: Worksheet, row: int, labels: Sequence[str], start_col: int = 1) -> None:
    for i, label in enumerate(labels):
        c = ws.cell(row, start_col + i, label)
        c.font = WHITE_BOLD
        c.fill = HEADER_FILL
        left = i == 0 or label in TEXT_HEADERS
        c.alignment = Alignment(
            horizontal="left" if left else "right", vertical="center", indent=1 if left else 0
        )
    ws.row_dimensions[row].height = 20


def _num(value: Decimal | None) -> float | None:
    """openpyxl writes floats; amounts are rounded to cents first so no noise reaches Excel."""
    return None if value is None else float(value.quantize(Decimal("0.01")))


def _footer(ws: Worksheet, row: int) -> None:
    today = dt.date.today()
    ws.cell(
        row,
        1,
        f"Generated by OpenVariance {__version__} on "
        f"{today:%B} {today.day}, {today.year}. "
        "Blue = input, black = formula.",
    ).font = MUTED


def export_variance(
    report: VarianceReport,
    path: str | Path,
    *,
    bridge: Bridge | None = None,
    commentary: Sequence[str] = (),
    company: str = "",
) -> Path:
    if bridge is not None:
        bridge = bridge.condensed(9)
    wb = Workbook()
    dash = wb.active
    dash.title = "Dashboard"
    var = wb.create_sheet("Variance")
    rows = _variance_sheet(var, report, company)
    bridge_rows = _bridge_sheet(wb.create_sheet("Bridge"), bridge, report) if bridge else None
    _dashboard_sheet(dash, report, rows, bridge_rows, commentary, company)
    _notes_sheet(wb.create_sheet("Notes"), report, bridge)
    for ws in wb.worksheets:
        ws.sheet_properties.tabColor = theme.xl(theme.GREEN)
        ws.page_setup.orientation = "landscape"
        ws.page_setup.fitToWidth = 1
        ws.sheet_properties.pageSetUpPr.fitToPage = True
    path = Path(path)
    wb.save(path)
    return path


def _variance_sheet(ws: Worksheet, report: VarianceReport, company: str) -> dict[str, int]:
    _title(ws, f"{company or 'Variance analysis'}", report.title, 7)
    _header(
        ws,
        4,
        [
            "Line",
            report.actual_label,
            report.baseline_label,
            "Variance",
            "Var %",
            "F/U",
            "Direction",
        ],
    )
    ws.column_dimensions["A"].width = 40
    for letter in "BCDE":
        ws.column_dimensions[letter].width = 15
    ws.column_dimensions["F"].width = 7
    ws.column_dimensions["G"].width = 10
    ws.column_dimensions["G"].hidden = True
    ws.freeze_panes = "B5"
    row_of: dict[str, int] = {}
    r = 5
    for vrow in report.rows:
        spec = LINES[vrow.line]
        row_of[vrow.line] = r
        label = ws.cell(r, 1, vrow.label)
        label.alignment = Alignment(indent=1 + vrow.depth * 2)
        ws.cell(r, 7, spec.direction).font = MUTED
        dept_rows = []
        for i, d in enumerate(vrow.departments, start=1):
            dr = r + i
            ws.cell(dr, 1, d.department).alignment = Alignment(indent=3 + vrow.depth * 2)
            ws.cell(dr, 1).font = MUTED
            for col, value in ((2, d.actual), (3, d.baseline)):
                cell = ws.cell(dr, col, _num(value) if value is not None else 0)
                cell.font = INPUT
                cell.number_format = NUM
            ws.cell(dr, 7, spec.direction).font = MUTED
            _variance_formulas(ws, dr, muted=True)
            ws.row_dimensions[dr].outline_level = 1
            dept_rows.append(dr)
        if vrow.is_total:
            for col in (2, 3):
                ws.cell(r, col).font = BOLD
            label.font = BOLD
        elif dept_rows:
            for col in (2, 3):
                letter = get_column_letter(col)
                ws.cell(
                    r, col, f"=SUM({letter}{dept_rows[0]}:{letter}{dept_rows[-1]})"
                ).font = FORMULA
        else:
            for col, value in ((2, vrow.actual), (3, vrow.baseline)):
                ws.cell(r, col, _num(value) if value is not None else 0).font = INPUT
        for col in (2, 3):
            ws.cell(r, col).number_format = NUM
        _variance_formulas(ws, r, bold=vrow.is_total)
        if vrow.is_total:
            for col in range(1, 7):
                ws.cell(r, col).border = Border(top=RULE)
        if vrow.line in ("operating_income", "net_income"):
            for col in range(1, 7):
                ws.cell(r, col).border = Border(top=TOTAL_RULE, bottom=TOTAL_RULE)
        r += 1 + len(dept_rows)
    # Computed lines reference their components' rows, so the sheet recalculates on its own.
    for vrow in report.rows:
        if not vrow.is_total:
            continue
        rr = row_of[vrow.line]
        for col in (2, 3):
            letter = get_column_letter(col)
            terms = [
                f"{'+' if sign > 0 else '-'}{letter}{row_of[c]}"
                for sign, c in LINES[vrow.line].formula
                if c in row_of
            ]
            formula = "".join(terms).lstrip("+") or "0"
            ws.cell(rr, col, f"={formula}")
    last = r - 1
    ws.conditional_formatting.add(
        f"D5:D{last}",
        CellIsRule(
            operator="lessThan", formula=["-0.005"], font=Font(color=theme.xl(theme.UNFAVORABLE))
        ),
    )
    ws.conditional_formatting.add(
        f"D5:D{last}",
        CellIsRule(
            operator="greaterThan", formula=["0.005"], font=Font(color=theme.xl(theme.FAVORABLE))
        ),
    )
    ws.conditional_formatting.add(
        f"F5:F{last}",
        FormulaRule(
            formula=['F5="U"'],
            font=Font(bold=True, color=theme.xl(theme.UNFAVORABLE)),
            fill=PatternFill("solid", fgColor=theme.xl(theme.UNFAVORABLE_BG)),
        ),
    )
    ws.conditional_formatting.add(
        f"F5:F{last}",
        FormulaRule(
            formula=['F5="F"'],
            font=Font(bold=True, color=theme.xl(theme.FAVORABLE)),
            fill=PatternFill("solid", fgColor=theme.xl(theme.FAVORABLE_BG)),
        ),
    )
    ws.cell(
        last + 2,
        1,
        "Variance = (actual − baseline) × direction, so positive is always "
        "favorable. Var % divides by the absolute baseline; n/m means the "
        "baseline is zero.",
    ).font = MUTED
    _footer(ws, last + 3)
    ws.sheet_properties.outlinePr.summaryBelow = False
    return row_of


def _variance_formulas(ws: Worksheet, r: int, bold: bool = False, muted: bool = False) -> None:
    font = BOLD if bold else (MUTED if muted else FORMULA)
    d = ws.cell(r, 4, f"=(B{r}-C{r})*G{r}")
    e = ws.cell(r, 5, f'=IF(C{r}=0,"n/m",D{r}/ABS(C{r}))')
    f = ws.cell(r, 6, f'=IF(ROUND(D{r},2)=0,"",IF(D{r}>0,"F","U"))')
    d.number_format, e.number_format = NUM, PCT
    for c in (d, e, f):
        c.font = font
    e.alignment = Alignment(horizontal="right")
    f.alignment = Alignment(horizontal="center")


def _bridge_sheet(ws: Worksheet, bridge: Bridge, report: VarianceReport) -> dict[str, Any]:
    _title(
        ws,
        f"{bridge.metric} bridge",
        f"{bridge.start_label} to {bridge.end_label}. "
        f"Method: {'Shapley driver attribution' if bridge.method == 'shapley' else 'line items'}.",
        11,
    )
    _header(ws, 4, ["Step", "Impact", "Running total", "Detail"])
    ws.column_dimensions["A"].width = 30
    ws.column_dimensions["B"].width = 15
    ws.column_dimensions["C"].width = 15
    ws.column_dimensions["D"].width = 70
    r = 5
    ws.cell(r, 1, bridge.start_label).font = BOLD
    ws.cell(r, 2, _num(bridge.start)).font = INPUT
    ws.cell(r, 3, f"=B{r}").font = BOLD
    first_step = r + 1
    for step in bridge.steps:
        r += 1
        ws.cell(r, 1, step.label).alignment = Alignment(indent=1)
        ws.cell(r, 2, _num(step.amount)).font = INPUT
        ws.cell(r, 3, f"=C{r - 1}+B{r}").font = FORMULA
        ws.cell(r, 4, step.detail).font = MUTED
    last_step = r
    r += 1
    end_row = r
    ws.cell(r, 1, bridge.end_label).font = BOLD
    ws.cell(r, 2, f"=B5+SUM(B{first_step}:B{last_step})" if bridge.steps else "=B5").font = BOLD
    ws.cell(r, 3, f"=B{r}").font = BOLD
    for col in range(1, 5):
        ws.cell(r, col).border = Border(top=TOTAL_RULE)
    for rr in range(5, r + 1):
        for col in (2, 3):
            ws.cell(rr, col).number_format = NUM
    r += 2
    ws.cell(r, 1, f"Reported {bridge.end_label.lower()}").font = FORMULA
    ws.cell(r, 2, _num(bridge.end)).font = INPUT
    ws.cell(r, 2).number_format = NUM
    ws.cell(r + 1, 1, "Check: bridge ties (should be 0)").font = BOLD
    check = ws.cell(r + 1, 2, f"=ROUND(B{end_row}-B{r},2)")
    check.font = BOLD
    check.number_format = NUM2
    ws.conditional_formatting.add(
        f"B{r + 1}",
        CellIsRule(
            operator="notEqual",
            formula=["0"],
            fill=PatternFill("solid", fgColor=theme.xl(theme.UNFAVORABLE_BG)),
        ),
    )
    check_row = r + 1

    # Chart helper columns (hidden): a waterfall as a stacked bar with invisible bases.
    # Positive and negative regions are split so steps that cross zero still draw correctly.
    helper = [
        "Label",
        "Base +",
        "Base −",
        "Increase +",
        "Increase −",
        "Decrease +",
        "Decrease −",
        "Total +",
        "Total −",
    ]
    hc = 6  # column F
    for i, label in enumerate(helper):
        ws.cell(4, hc + i, label).font = MUTED
    rows = [5, *range(first_step, last_step + 1), end_row]
    for out_r, src in enumerate(rows, start=5):
        ws.cell(out_r, hc, f"=A{src}")
        is_total = src in (5, end_row)
        prev = f"(C{src}-B{src})"
        new = f"C{src}"
        lo, hi = f"MIN({prev},{new})", f"MAX({prev},{new})"
        if is_total:
            ws.cell(out_r, hc + 7, f"=MAX(C{src},0)")
            ws.cell(out_r, hc + 8, f"=MIN(C{src},0)")
            for k in range(1, 7):
                ws.cell(out_r, hc + k, 0)
        else:
            ws.cell(out_r, hc + 1, f"=MAX({lo},0)")
            ws.cell(out_r, hc + 2, f"=MIN({hi},0)")
            pos_len = f"(MAX({hi},0)-MAX({lo},0))"
            neg_len = f"(MIN({lo},0)-MIN({hi},0))"
            ws.cell(out_r, hc + 3, f"=IF(B{src}>=0,{pos_len},0)")
            ws.cell(out_r, hc + 4, f"=IF(B{src}>=0,{neg_len},0)")
            ws.cell(out_r, hc + 5, f"=IF(B{src}<0,{pos_len},0)")
            ws.cell(out_r, hc + 6, f"=IF(B{src}<0,{neg_len},0)")
            ws.cell(out_r, hc + 7, 0)
            ws.cell(out_r, hc + 8, 0)
    last_helper = 4 + len(rows)
    for c in range(hc, hc + len(helper)):
        ws.column_dimensions[get_column_letter(c)].hidden = True
    _footer(ws, check_row + 2)
    return {
        "sheet": ws,
        "first": 5,
        "last": last_helper,
        "col": hc,
        "check": f"Bridge!B{check_row}",
        "axis_min": _axis_min(bridge),
    }


def _axis_min(bridge: Bridge) -> float | None:
    """Start the value axis above zero when the drivers are small next to the totals.

    Same rule as the HTML dashboard: only when every level is positive, and the chart
    title says where the axis starts so the truncation is never hidden.
    """
    levels = [bridge.start]
    for step in bridge.steps:
        levels.append(levels[-1] + step.amount)
    low, high = min(levels), max(levels)
    if low <= 0 or low <= (high - low) * 2:
        return None
    span = high - low
    raw = max(low - span * Decimal("1.2"), Decimal(0))
    magnitude = Decimal(10) ** (len(str(int(span))) - 1)
    return float((raw / magnitude).to_integral_value(rounding="ROUND_FLOOR") * magnitude)


def _waterfall_chart(bridge_rows: dict[str, Any], title: str) -> BarChart:
    ws, first, last, hc = (
        bridge_rows["sheet"],
        bridge_rows["first"],
        bridge_rows["last"],
        bridge_rows["col"],
    )
    chart = BarChart()
    chart.type = "col"
    chart.grouping = "stacked"
    chart.overlap = 100
    chart.gapWidth = 60
    chart.title = title
    chart.legend = None
    chart.visible_cells_only = False  # the helper columns are hidden; plot them anyway
    if bridge_rows.get("axis_min") is not None:
        chart.y_axis.scaling.min = bridge_rows["axis_min"]
        chart.title = f"{title} (axis starts at {bridge_rows['axis_min']:,.0f})"
    chart.height = 8
    chart.width = 22
    chart.y_axis.numFmt = "#,##0"
    chart.y_axis.delete = False
    chart.x_axis.delete = False
    data = Reference(ws, min_col=hc + 1, max_col=hc + 8, min_row=4, max_row=last)
    cats = Reference(ws, min_col=hc, min_row=first, max_row=last)
    chart.add_data(data, titles_from_data=True)
    chart.set_categories(cats)
    colors = [
        None,
        None,
        theme.FAVORABLE_BAR,
        theme.FAVORABLE_BAR,
        theme.UNFAVORABLE_BAR,
        theme.UNFAVORABLE_BAR,
        theme.GREEN_DARK,
        theme.GREEN_DARK,
    ]
    for series, color in zip(chart.series, colors, strict=False):
        gp = GraphicalProperties()
        if color is None:
            gp.noFill = True
            gp.line.noFill = True
        elif color == theme.UNFAVORABLE_BAR:
            gp.pattFill = PatternFillProperties(prst="wdUpDiag")
            gp.pattFill.foreground = ColorChoice(srgbClr=color.lstrip("#"))
            gp.pattFill.background = ColorChoice(srgbClr="F4B6B4")
            gp.line.noFill = True
        else:
            gp.solidFill = color.lstrip("#")
            gp.line.noFill = True
        series.graphicalProperties = gp
    return chart


def _dashboard_sheet(
    ws: Worksheet,
    report: VarianceReport,
    rows: dict[str, int],
    bridge_rows: dict[str, Any] | None,
    commentary: Sequence[str],
    company: str,
) -> None:
    _title(ws, f"{company or 'OpenVariance'}", report.title, 12)
    for col in range(1, 13):
        ws.column_dimensions[get_column_letter(col)].width = 13
    tiles = [
        k
        for k in ("revenue", "gross_profit", "ebitda", "operating_income", "net_income")
        if k in rows
    ][:4]
    for i, key in enumerate(tiles):
        c0 = 1 + i * 3
        r = rows[key]
        for rr in (4, 5, 6):
            ws.merge_cells(start_row=rr, start_column=c0, end_row=rr, end_column=c0 + 2)
        label = ws.cell(4, c0, LINES[key].label)
        label.font = MUTED
        value = ws.cell(5, c0, f"=Variance!B{r}")
        value.font = _font(bold=True, size=18, color=theme.xl(theme.INK))
        value.number_format = NUM
        value.alignment = Alignment(horizontal="left", indent=1)
        delta = ws.cell(
            6,
            c0,
            f'=TEXT(Variance!D{r},"+#,##0;-#,##0;0")&" vs {report.baseline_label.lower()}  "&Variance!F{r}',
        )
        delta.font = _font(size=10, color=theme.xl(theme.INK_MUTED))
        for rr in (4, 5, 6):
            for cc in range(c0, c0 + 3):
                ws.cell(rr, cc).fill = TINT_FILL
    r = 8
    if commentary:
        ws.cell(r, 1, "Summary").font = BOLD
        for sentence in commentary:
            r += 1
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=12)
            cell = ws.cell(r, 1, sentence)
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            ws.row_dimensions[r].height = 30
        r += 2
    if bridge_rows:
        chart = _waterfall_chart(
            bridge_rows,
            f"{report.headline.label}: "
            f"{report.baseline_label.lower()} to {report.actual_label.lower()}",
        )
        ws.add_chart(chart, f"A{r}")
        r += 18
        ws.cell(r, 1, "Bridge check (should be 0)").font = MUTED
        chk = ws.cell(r, 4, f"={bridge_rows['check']}")
        chk.number_format = NUM2
        chk.font = MUTED
        r += 1
    _footer(ws, r + 1)


def _notes_sheet(ws: Worksheet, report: VarianceReport, bridge: Bridge | None) -> None:
    _title(ws, "Notes", "How to read this workbook", 2)
    ws.column_dimensions["A"].width = 28
    ws.column_dimensions["B"].width = 100
    notes = [
        (
            "Comparison",
            f"{report.actual_label} vs {report.baseline_label}, periods "
            f"{', '.join(report.periods)}",
        ),
        (
            "Sign convention",
            "Variance = (actual − baseline) × direction. Direction is +1 for "
            "revenue and profit lines and −1 for costs, so a positive variance "
            "is always favorable (F) and a negative one unfavorable (U).",
        ),
        (
            "Percent variance",
            "Variance ÷ |baseline|. Using the absolute baseline keeps the sign "
            "meaningful when the baseline is a loss. n/m = baseline is zero.",
        ),
        (
            "Materiality",
            f"Lines flagged in the report pass ${report.thresholds.amount:,} or "
            f"{report.thresholds.pct * 100:.0f}% of baseline.",
        ),
        (
            "Department detail",
            "Rows grouped under a line (use the outline buttons on the left) "
            "are its departments; the line is their SUM.",
        ),
    ]
    if bridge is not None:
        notes.append(
            (
                "Bridge method",
                "Shapley attribution: each driver gets its average effect over every order "
                "the drivers could change in, so contributions add up exactly and no driver "
                "is favored by going first. Rounded to the cent with largest remainders."
                if bridge.method == "shapley"
                else "Line-item bridge: shows where the change landed. Add driver data to see why.",
            )
        )
        notes.extend(("Note", n) for n in bridge.notes)
    for i, (k, v) in enumerate(notes, start=4):
        ws.cell(i, 1, k).font = BOLD
        ws.cell(i, 2, v).alignment = Alignment(wrap_text=True, vertical="top")
        ws.cell(i, 1).alignment = Alignment(vertical="top")
        ws.row_dimensions[i].height = 32
    _footer(ws, len(notes) + 6)


